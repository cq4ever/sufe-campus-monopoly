export type Dimension = "J" | "N" | "F" | "P";
export interface Option {
  text: string;
  value: number;
  night: boolean;
}
export interface Question {
  dimension: Dimension;
  text: string;
  options: Option[];
}
function question(
  dimension: Dimension,
  text: string,
  texts: string[],
  night: number[] = [],
): Question {
  return {
    dimension,
    text,
    options: texts.map((text, i) => ({
      text,
      value: [2, 1, -1, -2][i],
      night: night.includes(i),
    })),
  };
}
